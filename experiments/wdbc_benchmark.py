"""
experiments/wdbc_benchmark.py — Appendix: classic WDBC benchmark (not used by the app).

The Wisconsin Diagnostic Breast Cancer data (30 nuclear features from
fine-needle aspirates) is a different problem from the app's mammographic
risk model, and nearly any classifier reaches AUROC ≈ 0.99 on it. It is kept
here only as a reproducible appendix: stratified 10-fold CV of five classic
models, mean ± SD across folds. No thresholds are tuned.

Run:  python experiments/wdbc_benchmark.py   → reports/wdbc_benchmark.md
"""
from __future__ import annotations

import sys
import warnings
from pathlib import Path

import lightgbm as lgb
import numpy as np
import xgboost as xgb
from sklearn.datasets import load_breast_cancer
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold, cross_validate
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC

ROOT = Path(__file__).parent.parent
OUT = ROOT / "reports" / "wdbc_benchmark.md"

MODELS = {
    "Logistic regression": Pipeline([("scale", StandardScaler()),
                                     ("lr", LogisticRegression(max_iter=5000))]),
    "SVM (RBF)": Pipeline([("scale", StandardScaler()), ("svm", SVC(random_state=42))]),
    "Random forest": RandomForestClassifier(n_estimators=300, random_state=42, n_jobs=-1),
    "LightGBM": lgb.LGBMClassifier(n_estimators=200, learning_rate=0.05, num_leaves=15,
                                   random_state=42, verbose=-1),
    "XGBoost": xgb.XGBClassifier(n_estimators=300, learning_rate=0.05, max_depth=4,
                                 subsample=0.8, colsample_bytree=0.8, eval_metric="logloss",
                                 random_state=42, verbosity=0),
}


def main() -> int:
    data = load_breast_cancer()
    X, y = data.data, 1 - data.target            # 1 = malignant
    cv = StratifiedKFold(10, shuffle=True, random_state=42)
    rows = []
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        for name, model in MODELS.items():
            res = cross_validate(model, X, y, cv=cv, scoring=["roc_auc", "accuracy", "recall"])
            rows.append((name, res["test_roc_auc"], res["test_accuracy"], res["test_recall"]))
            print(f"{name:<22} AUROC {res['test_roc_auc'].mean():.4f} ± {res['test_roc_auc'].std():.4f}")

    lines = [
        "# Appendix: WDBC benchmark",
        "",
        "Generated by `experiments/wdbc_benchmark.py`. **Not used by the app.**",
        "",
        f"Wisconsin Diagnostic Breast Cancer (`sklearn.datasets.load_breast_cancer`): "
        f"{len(y)} cases, {X.shape[1]} features, {int(y.sum())} malignant. Stratified 10-fold "
        "CV over all cases; mean ± SD across folds. Recall uses the default 0.5 threshold.",
        "",
        "| Model | AUROC | Accuracy | Recall |",
        "|---|---|---|---|",
    ]
    for name, auc, acc, rec in rows:
        lines.append(f"| {name} | {auc.mean():.4f} ± {auc.std():.4f} | "
                     f"{acc.mean():.2%} ± {acc.std():.2%} | {rec.mean():.2%} ± {rec.std():.2%} |")
    lines += ["", "Every model lands near AUROC 0.99, so WDBC does not discriminate between "
              "methods; that is why the main project focuses on the harder mammographic task.", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
