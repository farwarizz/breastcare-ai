def render_targets() -> dict[Path, str]:
    md, kb, ev = load_metadata(), knowledge_base_stats(), evaluation_summaries()
    blocks = {"results": lambda prefix: results_block(md, kb, prefix),
              "model-card": lambda prefix: model_card_block(md),
              "assistant": lambda prefix: assistant_block(ev, kb, prefix)}
    out = {}
    for path, names in BLOCK_TARGETS.items():
        text = path.read_text(encoding="utf-8")
        prefix = "reports/figures/" if path.parent == ROOT else "../reports/figures/"
        for name in names:
            pattern = re.compile(rf"<!-- BEGIN GENERATED: {name}\b.*?<!-- END GENERATED: {name} -->", re.S)
            if not pattern.search(text):
                raise SystemExit(f"ERROR: no '{name}' generated block in {path.relative_to(ROOT)}")
            text = pattern.sub(lambda _, n=name: blocks[n](prefix), text, count=1)
        out[path] = text
    out[REPORT] = evaluation_report(md, kb)
    out[RAG_REPORT] = rag_report(ev, kb)
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description="Render doc metrics from model metadata.")
    parser.add_argument("--check", action="store_true", help="exit 1 if anything is out of date")
    args = parser.parse_args()
    stale = []
    for path, new in render_targets().items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if new != old:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(new, encoding="utf-8", newline="\n")
    for path in stale:
        print(f"{path.relative_to(ROOT)} {'is out of date' if args.check else 'updated'}")
    if args.check and stale:
        print("Run `python scripts/update_readme_metrics.py` to refresh.")
        return 1
    if not stale:
        print("Generated docs already match models/model_metadata.json.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
