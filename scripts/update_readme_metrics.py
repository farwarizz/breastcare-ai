"""
scripts/update_readme_metrics.py — Render the metrics block in README.md and
docs/DESIGN.md from models/model_metadata.json (plus the knowledge-base index).

Numbers in the docs are never typed by hand: retrain, then run this script.
The block lives between the METRICS:START / METRICS:END markers.

Run:  python scripts/update_readme_metrics.py           # rewrite the blocks
      python scripts/update_readme_metrics.py --check   # exit 1 if any block is stale
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT))
from src.model_info import load_metadata, knowledge_base_stats

TARGETS = [ROOT / "README.md", ROOT / "docs" / "DESIGN.md"]
START = ("<!-- METRICS:START (generated by scripts/update_readme_metrics.py "
         "from models/model_metadata.json; do not edit by hand) -->")
END = "<!-- METRICS:END -->"
BLOCK_RE = re.compile(r"<!-- METRICS:START.*?-->.*?<!-- METRICS:END -->", re.S)


def pct(v: float) -> str:
    return f"{v:.2f}%"


def render(md: dict, kb: dict) -> str:
    lg = md["lgbm_mammographic"]
    xg = md["xgboost_wdbc"]
    mm = md["datasets"]["mammographic"]
    cv_rows = "\n".join(
        f"| {name} | {m['auc']:.4f} ± {m['auc_std']:.4f} | {pct(m['accuracy'])} | {pct(m['recall'])} |"
        for name, m in md["cv_comparison"].items()
    )
    return f"""{START}
**Served model: LightGBM on UCI Mammographic Mass** (test split n = {lg['n_test']}, \
train n = {lg['n_train']}, decision threshold {md['lgbm_optimal_threshold']:.3f})

| Metric | Value |
|---|---|
| ROC-AUC | {lg['auc']:.4f} |
| Accuracy | {pct(lg['accuracy'])} |
| Sensitivity (recall) | {pct(lg['recall'])} |
| Specificity | {pct(lg['specificity'])} |
| Precision | {pct(lg['precision'])} |
| F1 | {pct(lg['f1'])} |
| False negatives / false positives | {lg['false_negatives']} / {lg['false_positives']} |

**Evaluation protocol (from the metadata):** {md['evaluation_protocol']}

**Research benchmark: XGBoost on WDBC** (not used by the app; test n = {xg['n_test']}): \
AUC {xg['auc']:.4f} · accuracy {pct(xg['accuracy'])} · sensitivity {pct(xg['recall'])} · \
specificity {pct(xg['specificity'])}

<details><summary>5-model stratified 10-fold CV on the WDBC training split</summary>

| Model | AUC (mean ± SD) | Accuracy | Recall |
|---|---|---|---|
{cv_rows}

</details>

**Data:** {mm['name']} (UCI id {mm['uci_id']}): {mm['raw_rows']} raw rows, {mm['clean_rows']} \
after dropping rows with missing values ({mm['benign']} benign / {mm['malignant']} malignant). \
**Knowledge base:** {kb['n_chunks']} chunks indexed from {kb['n_indexed_sources']} of \
{kb['n_available_sources']} source documents ({kb['embedding_dim']}-d {kb['embedder']} embeddings).
{END}"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Render doc metrics from model metadata.")
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 if any block is out of date")
    args = parser.parse_args()

    block = render(load_metadata(), knowledge_base_stats())
    stale = []
    for path in TARGETS:
        text = path.read_text(encoding="utf-8")
        if not BLOCK_RE.search(text):
            print(f"ERROR: no METRICS:START/END markers in {path.relative_to(ROOT)}")
            return 1
        updated = BLOCK_RE.sub(lambda _: block, text, count=1)
        if updated != text:
            stale.append(path)
            if not args.check:
                path.write_text(updated, encoding="utf-8", newline="\n")

    for path in stale:
        verb = "is out of date" if args.check else "updated"
        print(f"{path.relative_to(ROOT)} {verb}")
    if args.check and stale:
        print("Run `python scripts/update_readme_metrics.py` to refresh.")
        return 1
    if not stale:
        print("Metrics blocks already match models/model_metadata.json.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
