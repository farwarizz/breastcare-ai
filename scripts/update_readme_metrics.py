"""
scripts/update_readme_metrics.py — Render every number in the docs from saved artifacts.

Sources: models/model_metadata.json (written by `python -m src.ml.train`) and
the knowledge-base index. Outputs:
  - README.md, docs/DESIGN.md   block "results"
  - docs/MODEL_CARD.md          block "model-card"
  - reports/evaluation.md       whole file
Blocks sit between <!-- BEGIN GENERATED: name --> and <!-- END GENERATED: name -->.
Interpretive sentences are computed from the numbers, so they cannot go stale.

Run:  python scripts/update_readme_metrics.py           # rewrite
      python scripts/update_readme_metrics.py --check   # exit 1 if anything is stale
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT))
from src.model_info import knowledge_base_stats, load_metadata

BLOCK_TARGETS = {
    ROOT / "README.md": "results",
    ROOT / "docs" / "DESIGN.md": "results",
    ROOT / "docs" / "MODEL_CARD.md": "model-card",
}
REPORT = ROOT / "reports" / "evaluation.md"
NOTE = "generated by scripts/update_readme_metrics.py from models/model_metadata.json; do not edit by hand"


# ── formatting helpers ───────────────────────────────────────────
def ci(m: dict, d: int = 2) -> str:
    """'0.90 (0.84–0.94)'; uses 'to' when a bound is negative, so minus signs stay readable."""
    lo, hi = m["ci"]
    sep = " to " if lo < 0 or hi < 0 else "–"
    return f"{m['value']:.{d}f} ({lo:.{d}f}{sep}{hi:.{d}f})"


def signed(m: dict, d: int = 3) -> str:
    return f"{m['value']:+.{d}f} ({m['ci'][0]:+.{d}f} to {m['ci'][1]:+.{d}f})"


def includes(m: dict, x: float) -> bool:
    return m["ci"][0] <= x <= m["ci"][1]


def figure(name: str, alt: str, prefix: str) -> str:
    return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="{prefix}{name}_dark.png">'
            f'<img src="{prefix}{name}_light.png" alt="{alt}" width="100%"></picture>')


# ── interpretive sentences (computed) ────────────────────────────
def difference_sentence(diff: dict, what: str) -> str:
    if includes(diff, 0.0):
        return f"no significant difference in {what} (the 95% CI includes 0)"
    return f"a significant difference in {what} (the 95% CI excludes 0)"


def slope_sentence(slope: dict) -> str:
    if includes(slope, 1.0):
        return "consistent with ideal calibration (slope 1)"
    if slope["value"] > 1:
        return "underconfident on this test split (predictions less extreme than outcomes; slope > 1)"
    return "overconfident on this test split (predictions too extreme; slope < 1)"


def coverage_sentence(cov: dict, target: float) -> str:
    if includes(cov, target):
        return f"consistent with the {target:.0%} target"
    return f"{'below' if cov['value'] < target else 'above'} the {target:.0%} target on this split"


def dca_sentence(dca: dict, served_label: str) -> str:
    ts, nb, nb_all = dca["thresholds"], dca["net_benefit"][served_label], dca["treat_all"]
    gains = [t for t, a, b in zip(ts, nb, nb_all) if a - b > 0.005]
    at2 = abs(nb[0] - nb_all[0]) <= 0.005 if ts[0] == 0.02 else False
    first = (f"adds net benefit over biopsying everyone from a threshold of {gains[0]:.0%}"
             if gains else "never beats biopsying everyone")
    return (("matches 'biopsy everyone' at the 2% BI-RADS biopsy threshold and " if at2 else "")
            + first)


def subgroup_sentence(groups: dict) -> str:
    parts = [f"{g}: sensitivity {ci(v['sensitivity'])}, n malignant = {v['n_malignant']}"
             for g, v in groups.items()]
    sens = {g: v["sensitivity"]["value"] for g, v in groups.items()}
    low = min(sens, key=sens.get)
    gap = max(sens.values()) - sens[low]
    tail = (f"; sensitivity is {gap:.2f} lower in the {low} group at the global threshold"
            if gap >= 0.1 else "")
    return "; ".join(parts) + tail


# ── blocks ───────────────────────────────────────────────────────
def results_block(md: dict, kb: dict, prefix: str) -> str:
    s, c = md["served_model"], md["challenger_model"]
    st, ct = s["test"], c["test"]
    comp = md["comparisons"]
    conf, hs = st["conformal"], st["high_sensitivity_operating_point"]
    target = s["conformal"]["coverage_target"]
    br = comp["birads_reference"]
    rows = [
        ("AUROC", ci(st["auroc"]), ci(ct["auroc"])),
        ("AUPRC", ci(st["auprc"]), ci(ct["auprc"])),
        ("Brier score (lower is better)", ci(st["brier"], 3), ci(ct["brier"], 3)),
        ("Calibration slope (ideal 1)", ci(st["calibration_slope"]), ci(ct["calibration_slope"])),
        ("Calibration intercept (ideal 0)", ci(st["calibration_intercept"]), ci(ct["calibration_intercept"])),
        (f"Sensitivity at its threshold", ci(st["sensitivity"]), ci(ct["sensitivity"])),
        (f"Specificity at its threshold", ci(st["specificity"]), ci(ct["specificity"])),
        ("Decision threshold (chosen on dev data)", f"{st['threshold']:.3f}", f"{ct['threshold']:.3f}"),
    ]
    table = "\n".join(f"| {a} | {b} | {c_} |" for a, b, c_ in rows)
    sel = md["selection"]
    return f"""<!-- BEGIN GENERATED: results ({NOTE}) -->
**Served model: {s['label']}**, chosen by a fixed rule. {sel['rule']}
Held-out test set: n = {st['n']} ({st['n_malignant']} malignant), used once; 95% bootstrap CIs in brackets.

| Metric | {s['label']} (served) | {c['label']} (challenger) |
|---|---|---|
{table}

- **Served vs challenger:** AUROC difference {signed(comp['auroc_difference_served_minus_challenger'])}: \
{difference_sentence(comp['auroc_difference_served_minus_challenger'], 'AUROC')}.
- **Calibration:** the served model is {slope_sentence(st['calibration_slope'])}; intercept \
{ci(st['calibration_intercept'])}. Calibration step chosen on out-of-fold data: `{s['calibration']['method']}`.
- **{target:.0%} conformal prediction sets:** coverage {ci(conf['coverage'])} \
({coverage_sentence(conf['coverage'], target)}); benign {ci(conf['coverage_benign'])}, malignant \
{ci(conf['coverage_malignant'])}. {conf['share_single_label']['value']:.0%} of cases get a single label.
- **High-sensitivity operating point** (threshold {hs['threshold']:.2f}, chosen on development data): \
sensitivity {ci(hs['sensitivity'])}, specificity {ci(hs['specificity'])}.
- **Reference, radiologists' BI-RADS assessment** (ordinal category, n = {br['n']}): AUROC {ci(br['auroc_birads'])}.
- **Decision curve:** the served model {dca_sentence(md['decision_curve'], s['label'])}.
- **Subgroups ({md['subgroups']['by']}):** {subgroup_sentence(md['subgroups']['groups'])}.
- **Cross-validation vs test:** 5-fold CV AUROC on the fit split {s['cv']['cv_auroc']:.2f}; test AUROC \
{st['auroc']['value']:.2f}. The CV figure is the more conservative estimate for new data.

{figure('roc_pr', 'ROC and precision-recall curves', prefix)}
{figure('calibration', 'Calibration curve', prefix)}
{figure('decision_curve', 'Decision curve', prefix)}
{figure('conformal_sets', 'Conformal prediction sets', prefix)}

**Data:** {md['datasets']['mammographic']['name']} (UCI id {md['datasets']['mammographic']['uci_id']}): \
{md['datasets']['mammographic']['clean_rows']} cleaned cases. Split: fit {md['protocol']['n']['fit']} · \
conformal {md['protocol']['n']['conformal']} · test {md['protocol']['n']['test']}. \
**Knowledge base:** {kb['n_chunks']} chunks from {kb['n_indexed_sources']} of {kb['n_available_sources']} documents.
Full details: [reports/evaluation.md]({prefix.replace('figures/', '')}evaluation.md).
<!-- END GENERATED: results -->"""


def model_card_block(md: dict) -> str:
    s, st = md["served_model"], md["served_model"]["test"]
    sub = md["subgroups"]["groups"]
    sub_rows = "\n".join(
        f"| {g} | {v['n']} ({v['n_malignant']} malignant) | {ci(v['auroc'])} | {ci(v['sensitivity'])} | "
        f"{ci(v['specificity'])} |" for g, v in sub.items())
    params = ", ".join(f"{k}={v}" for k, v in s["params"].items())
    conf = s["conformal"]
    return f"""<!-- BEGIN GENERATED: model-card ({NOTE}) -->
| | |
|---|---|
| Model | {s['label']} ({params}) |
| Inputs | age, shape, margin, density (BI-RADS assessment excluded) |
| Output | calibrated P(malignant), {conf['coverage_target']:.0%} conformal prediction set, class at threshold {s['threshold']['value']:.3f} |
| Trained on | {s['trained_on']} of the UCI Mammographic Mass data |
| Calibration | `{s['calibration']['method']}` (chosen by CV Brier on out-of-fold predictions) |
| Conformal | {conf['method']}; Benign in set if p ≤ {conf['benign_if_p_le']:.3f}, Malignant if p ≥ {conf['malignant_if_p_ge']:.3f} |
| Evaluation | held-out test set, n = {st['n']}, 95% bootstrap CIs |

**Main metrics (test set):** AUROC {ci(st['auroc'])} · Brier {ci(st['brier'], 3)} · \
sensitivity {ci(st['sensitivity'])} · specificity {ci(st['specificity'])} · \
conformal coverage {ci(st['conformal']['coverage'])}.

**Subgroups ({md['subgroups']['by']}), at the global threshold:**

| Group | n | AUROC | Sensitivity | Specificity |
|---|---|---|---|---|
{sub_rows}
<!-- END GENERATED: model-card -->"""


def evaluation_report(md: dict, kb: dict) -> str:
    s, c = md["served_model"], md["challenger_model"]
    sel, comp = md["selection"], md["comparisons"]
    models = [("served", s), ("challenger", c)] + [("ablation", m) for m in md["ablation_models"].values()]
    cv_rows = "\n".join(
        f"| {r['family']} | {', '.join(f'{k}={v}' for k, v in r['params'].items())} | "
        f"{r['cv_logloss']:.4f} ± {r['cv_logloss_se']:.4f} | {r['cv_auroc']:.4f} |"
        for r in sorted(sel["cv_results"], key=lambda r: r["cv_logloss"]))
    cal_rows = "\n".join(
        f"| {m['label']} ({role}) | {', '.join(f'{k} {v:.5f}' for k, v in m['calibration']['cv_brier_by_method'].items())} | "
        f"`{m['calibration']['method']}` | {m['threshold']['value']:.3f} | {m['high_sensitivity_threshold']['value']:.3f} |"
        for role, m in models)
    keys = [("auroc", 2), ("auprc", 2), ("brier", 3), ("ece", 3), ("calibration_intercept", 2),
            ("calibration_slope", 2), ("sensitivity", 2), ("specificity", 2), ("ppv", 2), ("npv", 2)]
    metric_rows = "\n".join(
        f"| {k} | " + " | ".join(ci(m["test"][k], d) for _, m in models) + " |" for k, d in keys)
    head = " | ".join(f"{m['label']} ({role})" for role, m in models)
    conf = s["test"]["conformal"]
    conf_rows = "\n".join(f"| {k.replace('_', ' ')} | {ci(v)} |" for k, v in conf.items())
    br = comp["birads_reference"]
    abl = comp["monotone_ablation"]
    sub = md["subgroups"]["groups"]
    sub_rows = "\n".join(
        f"| {g} | {v['n']} | {v['n_malignant']} | {ci(v['auroc'])} | {ci(v['sensitivity'])} | "
        f"{ci(v['specificity'])} | {ci(v['calibration_intercept'])} |" for g, v in sub.items())
    dca = md["decision_curve"]
    dca_rows = "\n".join(
        f"| {t:.0%} | " + " | ".join(f"{dca['net_benefit'][lbl][i]:.3f}" for lbl in dca["net_benefit"])
        + f" | {dca['treat_all'][i]:.3f} | 0.000 |" for i, t in enumerate(dca["thresholds"]))
    dca_head = " | ".join(dca["net_benefit"])
    hs = s["test"]["high_sensitivity_operating_point"]
    versions = ", ".join(f"{k} {v}" for k, v in md["versions"].items())
    return f"""# Evaluation report

<!-- {NOTE} -->

## Protocol

{md['protocol']['description']}

- Split sizes: fit {md['protocol']['n']['fit']}, conformal {md['protocol']['n']['conformal']}, \
test {md['protocol']['n']['test']} (seed {md['protocol']['split_seed']}; row ids in `models/splits.json`).
- Risk categories: {md['protocol']['risk_categories']}.

## Model selection (5-fold CV on the fit split)

Rule: {sel['rule']} Best by CV: `{sel['best_overall_by_cv']}`; one-SE bound {sel['one_se_bound']:.4f}; \
**selected: `{sel['selected']}`**, challenger: `{sel['challenger']}`.

| Family | Parameters | CV log-loss (mean ± SE) | CV AUROC |
|---|---|---|---|
{cv_rows}

## Calibration and thresholds (out-of-fold predictions, fit split)

| Model | CV Brier by calibration method | Chosen | Youden threshold | High-sensitivity threshold |
|---|---|---|---|---|
{cal_rows}

## Test-set metrics (n = {s['test']['n']}, {s['test']['n_malignant']} malignant; 95% bootstrap CIs)

| Metric | {head} |
|---|{'---|' * len(models)}
{metric_rows}

Served model at its threshold: {s['test']['counts']}.

Paired differences (same bootstrap resamples):
- AUROC, served − challenger: {signed(comp['auroc_difference_served_minus_challenger'])}
- Brier, served − challenger: {signed(comp['brier_difference_served_minus_challenger'])}
- Monotone ablation, AUROC (monotone − unconstrained LightGBM): {signed(abl['auroc_difference_monotone_minus_unconstrained'])}
- Monotone ablation, Brier: {signed(abl['brier_difference_monotone_minus_unconstrained'])}

## Conformal prediction sets (served model, target {s['conformal']['coverage_target']:.0%} per class)

Fitted on the conformal split ({s['conformal']['n_calibration']['benign']} benign, \
{s['conformal']['n_calibration']['malignant']} malignant). Benign is in the set if p ≤ \
{s['conformal']['benign_if_p_le']:.3f}; Malignant if p ≥ {s['conformal']['malignant_if_p_ge']:.3f}.

| Test-set quantity | Value (95% CI) |
|---|---|
{conf_rows}

The guarantee holds on average over random calibration and test draws; a single split of this size can \
land below the target.

## High-sensitivity operating point

Threshold {hs['threshold']:.3f} (highest out-of-fold threshold with sensitivity ≥ 95%): \
sensitivity {ci(hs['sensitivity'])}, specificity {ci(hs['specificity'])}, NPV {ci(hs['npv'])}.
At this point, the specificity is the share of benign masses that fell below the threshold.

## Reference: radiologists' BI-RADS assessment

On {br['n']} test rows ({br['n_excluded']} excluded: {br['excluded_reason']}): BI-RADS AUROC \
{ci(br['auroc_birads'])}; served model on the same rows {ci(br['auroc_model_same_rows'])}; difference \
{signed(br['auroc_difference_model_minus_birads'])}. BI-RADS is a coarse management category \
(mostly 4 or 5 here), not a probability, so this is context rather than a head-to-head claim.

## Subgroups ({md['subgroups']['by']}; served model at its global threshold)

| Group | n | Malignant | AUROC | Sensitivity | Specificity | Calibration intercept |
|---|---|---|---|---|---|---|
{sub_rows}

## Decision curve (net benefit on the test set)

| Threshold | {dca_head} | Treat all | Treat none |
|---|{'---|' * len(dca['net_benefit'])}---|---|
{dca_rows}

## Figures

{figure('roc_pr', 'ROC and precision-recall curves', 'figures/')}
{figure('calibration', 'Calibration curve', 'figures/')}
{figure('decision_curve', 'Decision curve', 'figures/')}
{figure('conformal_sets', 'Conformal prediction sets', 'figures/')}

## Environment

{versions}. Knowledge base: {kb['n_chunks']} chunks from {kb['n_indexed_sources']} documents.
"""


def render_targets() -> dict[Path, str]:
    md, kb = load_metadata(), knowledge_base_stats()
    blocks = {"results": lambda prefix: results_block(md, kb, prefix),
              "model-card": lambda prefix: model_card_block(md)}
    out = {}
    for path, name in BLOCK_TARGETS.items():
        text = path.read_text(encoding="utf-8")
        pattern = re.compile(rf"<!-- BEGIN GENERATED: {name}\b.*?<!-- END GENERATED: {name} -->", re.S)
        if not pattern.search(text):
            raise SystemExit(f"ERROR: no '{name}' generated block in {path.relative_to(ROOT)}")
        prefix = "reports/figures/" if path.parent == ROOT else "../reports/figures/"
        out[path] = pattern.sub(lambda _: blocks[name](prefix), text, count=1)
    out[REPORT] = evaluation_report(md, kb)
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description="Render doc metrics from model metadata.")
    parser.add_argument("--check", action="store_true", help="exit 1 if anything is out of date")
    args = parser.parse_args()
    stale = []
    for path, new in render_targets().items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if new != old:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(new, encoding="utf-8", newline="\n")
    for path in stale:
        print(f"{path.relative_to(ROOT)} {'is out of date' if args.check else 'updated'}")
    if args.check and stale:
        print("Run `python scripts/update_readme_metrics.py` to refresh.")
        return 1
    if not stale:
        print("Generated docs already match models/model_metadata.json.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
