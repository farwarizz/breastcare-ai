# ── formatting helpers ───────────────────────────────────────────
def ci(m: dict, d: int = 2) -> str:
    """'0.90 (0.84–0.94)'; uses 'to' when a bound is negative, so minus signs stay readable."""
    lo, hi = m["ci"]
    sep = " to " if lo < 0 or hi < 0 else "–"
    return f"{m['value']:.{d}f} ({lo:.{d}f}{sep}{hi:.{d}f})"


def signed(m: dict, d: int = 3) -> str:
    return f"{m['value']:+.{d}f} ({m['ci'][0]:+.{d}f} to {m['ci'][1]:+.{d}f})"


def includes(m: dict, x: float) -> bool:
    return m["ci"][0] <= x <= m["ci"][1]


def figure(name: str, alt: str, prefix: str) -> str:
    return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="{prefix}{name}_dark.png">'
            f'<img src="{prefix}{name}_light.png" alt="{alt}" width="100%"></picture>')


# ── interpretive sentences (computed) ────────────────────────────
def difference_sentence(diff: dict, what: str) -> str:
    if includes(diff, 0.0):
        return f"no significant difference in {what} (the 95% CI includes 0)"
    return f"a significant difference in {what} (the 95% CI excludes 0)"


def slope_sentence(slope: dict) -> str:
    if includes(slope, 1.0):
        return "consistent with ideal calibration (slope 1)"
    if slope["value"] > 1:
        return "underconfident on this test split (predictions less extreme than outcomes; slope > 1)"
    return "overconfident on this test split (predictions too extreme; slope < 1)"


def coverage_sentence(cov: dict, target: float) -> str:
    if includes(cov, target):
        return f"consistent with the {target:.0%} target"
    return f"{'below' if cov['value'] < target else 'above'} the {target:.0%} target on this split"


def dca_sentence(dca: dict, served_label: str) -> str:
    ts, nb, nb_all = dca["thresholds"], dca["net_benefit"][served_label], dca["treat_all"]
    gains = [t for t, a, b in zip(ts, nb, nb_all) if a - b > 0.005]
    at2 = abs(nb[0] - nb_all[0]) <= 0.005 if ts[0] == 0.02 else False
    first = (f"adds net benefit over biopsying everyone from a threshold of {gains[0]:.0%}"
             if gains else "never beats biopsying everyone")
    return (("matches 'biopsy everyone' at the 2% BI-RADS biopsy threshold and " if at2 else "")
            + first)


def subgroup_sentence(groups: dict) -> str:
    parts = [f"{g}: sensitivity {ci(v['sensitivity'])}, n malignant = {v['n_malignant']}"
             for g, v in groups.items()]
    sens = {g: v["sensitivity"]["value"] for g, v in groups.items()}
    low = min(sens, key=sens.get)
    gap = max(sens.values()) - sens[low]
    tail = (f"; sensitivity is {gap:.2f} lower in the {low} group at the global threshold"
            if gap >= 0.1 else "")
    return "; ".join(parts) + tail


