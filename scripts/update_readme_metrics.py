# ── assistant evaluations (Phase 2) ──────────────────────────────
def pct(m: dict) -> str:
    """'83% (74–90%)' for a Wilson/bootstrap proportion; small denominators are shown as
    counts ('2/10 (6–51%)') so a percentage does not look more precise than it is."""
    lo, hi = m["ci"]
    if "n" in m and m["n"] < 20:
        return f"{m['k']}/{m['n']} ({lo:.0%}–{hi:.0%})"
    return f"{m['value']:.0%} ({lo:.0%}–{hi:.0%})"


def mode_label(mode: str) -> str:
    kind, _, emb = mode.replace("+rerank", "").partition(":")
    base = {"bm25": "BM25", "dense": f"dense ({emb})", "hybrid": f"hybrid BM25 + {emb} (RRF)"}[kind]
    return base + (" + cross-encoder re-ranking" if mode.endswith("+rerank") else "")


def retrieval_sentences(rag: dict, kb: dict) -> list[str]:
    sel, modes = rag["selection"], rag["modes"]
    chosen, best = sel["chosen"], sel["best"]
    cm, bm = modes[chosen]["metrics"], modes["bm25"]["metrics"]
    qc = rag["query_construction"]
    diff = qc["hit3_difference_bare_minus_prefixed"]
    served = ("the served mode" if kb["retrieval_mode"] == chosen
              else f"**config mismatch: the app serves `{kb['retrieval_mode']}`**")
    bestm = modes[best]
    comparison = (f"the best mode, `{best}`, reaches Hit@3 {pct(bestm['metrics']['hit@3'])} and MRR@10 "
                  f"{pct(bestm['metrics']['mrr@10'])} at {bestm['latency_ms']:.0f} ms per query"
                  if best != chosen else f"BM25 alone reaches Hit@3 {pct(bm['hit@3'])}")
    lines = [
        f"**Retrieval:** `{chosen}` ({mode_label(chosen)}), {served}, chosen by a pre-registered rule from "
        f"{len(modes)} modes. On {rag['n_answerable']} labelled questions: Hit@3 {pct(cm['hit@3'])}, "
        f"MRR@10 {pct(cm['mrr@10'])}, nDCG@5 {pct(cm['ndcg@5'])}, {cm_latency(modes[chosen])}; {comparison}.",
        f"**Query construction:** the question alone reaches Hit@3 {pct(qc['bare_question']['hit@3'])} against "
        f"{pct(qc['shap_prefix_plus_question']['hit@3'])} with the SHAP summary prepended "
        f"(paired difference {signed(diff, 2)}: {difference_sentence(diff, 'Hit@3')}); the app uses "
        f"`{kb['retrieval_query']}`. Explanation-only queries find the section describing a top feature "
        f"within three chunks for {rag['explanation_queries']['hit@3']:.0%} of {rag['explanation_queries']['n_cases']} cases.",
    ]
    return lines


def cm_latency(mode_result: dict) -> str:
    return f"{mode_result['latency_ms']:.0f} ms per query"


def model_mix(counts: dict) -> str:
    """'gemini-3.5-flash-lite ×50, gemini-2.5-flash ×2' — the models that actually answered."""
    return ", ".join(f"`{m}` ×{n}" for m, n in sorted(counts.items(), key=lambda kv: -kv[1])) or "none"


def answers_sentence(ans: dict) -> str:
    a, u = ans["answerable"], ans["unanswerable"]
    return (f"**Answers** (generated by {model_mix(ans['generation_models_used'])}; LLM judge "
            f"`{ans['judge_model']}`): on {ans['n_answerable']} answerable questions, {pct(a['answered_faithfully'])} "
            f"got an answer whose every claim the judge found in the retrieved documents (faithful when "
            f"answering: {pct(a['faithful_when_answering'])}; the pipeline's top-3 contained a labelled section for "
            f"{pct(a['retrieval_hit'])}); {pct(a['citations_correct'])} had only correct citations. On "
            f"{ans['n_unanswerable']} unanswerable questions it said the documents do not cover them "
            f"{pct(u['correct_abstention'])} of the time. The judge's agreement with a person is not yet measured "
            f"(`evals/judge_agreement_sheet.csv`).")


def safety_sentence(saf: dict) -> str:
    fa = saf["guard_false_alarms_on_benign_questions"]
    version = saf.get("held_out_version", "v1")
    parts = []
    for name, label in (("held_out", f"held-out set {version}, written after the safety rules were frozen"),
                        ("development", "development set, used to build the safety rules, so in-sample")):
        s = saf["sets"][name]
        g, b = s["summary"]["guarded"], s["summary"]["baseline"]
        n_adv = s["n_prompts"] - s["categories"].get("benign", 0)
        parts.append(f"{label} ({n_adv} adversarial prompts): attack success {pct(g['attack_success_rate'])} "
                     f"with the safety layers vs {pct(b['attack_success_rate'])} without; over-refusal of "
                     f"{s['categories'].get('benign', 0)} benign prompts {pct(g['over_refusal'])} vs "
                     f"{pct(b['over_refusal'])}")
    crisis = saf["sets"]["held_out"]["summary"]["guarded"]["by_category"].get("crisis")
    crisis_txt = f" Crisis prompts on the held-out set: {pct(crisis)} unsafe replies with the safety layers." if crisis else ""
    pre = saf.get("prefix_baseline")
    pre_txt = ""
    if pre:
        pg, pb = pre["summary"]["guarded"], pre["summary"]["baseline"]
        pre_txt = (f" Before the fixes, held-out v1 gave {pct(pg['attack_success_rate'])} with the safety layers vs "
                   f"{pct(pb['attack_success_rate'])} without (crisis {pct(pg['by_category']['crisis'])}); v1 is now part "
                   f"of the development set.")
    return (f"**Red team:** {parts[0]}.{crisis_txt} On the {parts[1]}.{pre_txt} The input guard blocked "
            f"{pct(fa['blocked'])} of the {fa['n']} benign retrieval questions. Judge `{saf['judge_model']}`.")


def staleness(ev: dict, kb: dict) -> dict:
    """Which saved assistant evaluations no longer describe the current code and index."""
    import hashlib
    from src.evals.redteam import HELDOUT_VERSION
    from src.rag.prompt_builder import SYSTEM_PROMPT
    out = {}
    ans = ev.get("answers")
    if ans:
        prov = ans.get("provenance") or {}
        if (prov.get("chunks_sha256") != kb.get("chunks_sha256")
                or prov.get("system_prompt_sha256") != hashlib.sha256(SYSTEM_PROMPT.encode()).hexdigest()):
            out["answers"] = ("generated before the current system prompt and knowledge base (Phase 2.1); "
                              "re-run `python -m src.evals.answers`")
    saf = ev.get("safety")
    prov = (saf or {}).get("provenance")
    if prov and not prov.get("frozen_code_evaluation", False):
        out["safety"] = ("NOT a frozen-code evaluation: the safety code differed from the freeze record or changed "
                         f"during the run (mismatched: {prov.get('mismatched')}); see provenance")
    elif saf and saf.get("held_out_version", "v1") != HELDOUT_VERSION:
        out["safety"] = (f"results of the pre-fix system on held-out {saf.get('held_out_version', 'v1')}; the run on "
                         f"held-out {HELDOUT_VERSION} with the Phase 2.1 fixes is not complete")
    return out


def assistant_block(ev: dict, kb: dict, prefix: str) -> str:
    stale = staleness(ev, kb)
    lines = []
    lines += (retrieval_sentences(ev["retrieval"], kb) if "retrieval" in ev
              else ["**Retrieval:** not run yet (`python -m src.evals.retrieval`)."])
    lines.append(answers_sentence(ev["answers"]) if "answers" in ev
                 else "**Answers:** not run yet (`python -m src.evals.answers`).")
    lines.append(safety_sentence(ev["safety"]) if "sets" in ev.get("safety", {})
                 else "**Red team:** not run yet (`python -m src.evals.redteam`).")
    if stale.get("answers"):
        lines = [l + f" **Stale: {stale['answers']}.**" if l.startswith("**Answers") else l for l in lines]
    if stale.get("safety"):
        lines = [l + f" **Stale: {stale['safety']}.**" if l.startswith("**Red team") else l for l in lines]
    body = "\n".join(f"- {line}" for line in lines)
    return f"""<!-- BEGIN GENERATED: assistant ({RAG_NOTE}) -->
Knowledge base: {kb['n_chunks']} chunks from {kb['n_indexed_sources']} fact-checked documents; retrieval `{kb['retrieval_mode']}`.
{body}
Full details: [reports/rag_evaluation.md]({prefix.replace('figures/', '')}rag_evaluation.md).
<!-- END GENERATED: assistant -->"""


